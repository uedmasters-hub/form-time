#!/usr/bin/env node
/**
 * Writes every dial's colours, exactly as the web app derives them, to
 * screensaver/macos/Resources/dial-themes.json for the macOS screen saver,
 * which draws the clock natively (see macos/Sources/ClockRenderer.swift).
 *
 * It compiles the app's own theme code (dial-palettes.ts, dial-theme.ts,
 * flat-dial.ts, theme/color.ts) with TypeScript and runs it, so the screen
 * saver can't drift from the app. CI checks the file is current:
 *
 *   node screensaver/scripts/export-themes.mjs          # write it
 *   node screensaver/scripts/export-themes.mjs --check  # fail if out of date
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const require = createRequire(import.meta.url);
const ts = require(path.join(root, 'node_modules', 'typescript'));

const sources = {
  'theme/color': 'src/theme/color.ts',
  'clock/dial-theme': 'src/features/clock/dial-theme.ts',
  'clock/dial-palettes': 'src/features/clock/dial-palettes.ts',
  'clock/flat-dial': 'src/features/clock/flat-dial.ts',
};

const out = fs.mkdtempSync(path.join(os.tmpdir(), 'formtime-themes-'));
for (const [name, file] of Object.entries(sources)) {
  let code = fs.readFileSync(path.join(root, file), 'utf8');
  code = code.replace(/'@\/theme\/color'/g, name.startsWith('clock/') ? "'../theme/color'" : "'./color'");
  const js = ts.transpileModule(code, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  fs.mkdirSync(path.dirname(path.join(out, name)), { recursive: true });
  fs.writeFileSync(path.join(out, `${name}.js`), js);
}

const palettes = require(path.join(out, 'clock/dial-palettes.js'));
const { flatDialFrom } = require(path.join(out, 'clock/flat-dial.js'));
fs.rmSync(out, { recursive: true, force: true });

const entry = (theme) => ({ ...theme, flat: flatDialFrom(theme) });
const themes = {
  note: 'Generated by screensaver/scripts/export-themes.mjs from the web app. Do not edit.',
  day: Object.fromEntries(palettes.DIALS.map((d) => [d.id, entry(palettes.dayDialTheme(d.id))])),
  night: Object.fromEntries(palettes.LUMES.map((l) => [l.id, entry(palettes.nightDialTheme(l.id))])),
};

const target = path.join(root, 'screensaver', 'macos', 'Resources', 'dial-themes.json');
const json = `${JSON.stringify(themes, null, 2)}\n`;
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== json) {
    console.error('dial-themes.json is out of date: run node screensaver/scripts/export-themes.mjs');
    process.exit(1);
  }
  console.log('dial-themes.json is current');
} else {
  fs.writeFileSync(target, json);
  console.log(`Wrote ${path.relative(root, target)} (${Object.keys(themes.day).length} day, ${Object.keys(themes.night).length} night)`);
}
