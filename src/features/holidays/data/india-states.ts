import type { Holiday, HolidaySource } from '../types';

/**
 * India — state and union-territory holidays for 2026, one list per state.
 *
 * Each list comes from the state government's own notification where its
 * document could be read ('official'), otherwise from a publication that
 * reproduces that notification (named in the source). October 2026 dates
 * were cross-checked against RBI's holidays under the Negotiable
 * Instruments Act for each state's regional office.
 *
 * 'P' → public: offices (and, for NI Act holidays, banks) closed statewide.
 * 'R' → for some: optional/restricted holidays, holidays for some offices,
 * districts or communities, or banks only — the note says which.
 *
 * National holidays and pan-India observances are added in holidays.ts, so
 * every state shows them even where its own list leaves them out.
 * Generated from the research notes; edit the rows, not the structure.
 */
const LUNAR = 'Date may shift with the moon sighting';
const OPTIONAL = 'Optional holiday';
const BANKS = 'Banks only';
const DOT = ' · ';

type Row = [start: string, name: string, kind: 'P' | 'R', note?: string];

function rows(list: Row[]): Holiday[] {
  return list.map(([start, name, kind, note]) => ({
    start,
    name,
    kind: kind === 'P' ? 'public' : 'restricted',
    ...(note ? { note } : null),
  }));
}

